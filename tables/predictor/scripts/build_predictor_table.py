HEADS = {"full_target_pcc": r"PCC $\uparrow$", "delta_pcc": r"$\Delta$PCC $\uparrow$",
         "raw_target_rmse": r"RMSE $\downarrow$", "E": r"$E$ $\uparrow$"}


def block_header(title, setting_label, metrics=METRICS):
    return "\n".join([
        r"\rowcolor[gray]{0.86}\multicolumn{"+str(3+len(metrics))+r"}{l}{\rule{0pt}{13pt}\textbf{"+title+r"}}\\[4pt]",
        r"\midrule[0.3pt]",
        r"\rowcolor[gray]{0.92}\ReCATableHead{"+setting_label+r"} & \ReCATableHead{\textit{n}} & \ReCATableHead{Method} & "
        +" & ".join(r"\ReCATableHead{"+HEADS[m]+"}" for m in metrics)+r" \\[4pt]",
        r"\midrule[0.5pt]",
    ])


def data_rows(rows, extended=False, show_difference=True, metrics=METRICS):
    lines = []
    prefixes = ("raw", "comparator", "difference") if show_difference else ("raw", "comparator")
    groups = {}
    for r in rows:
        grouping = r["target_line"] if extended else r["setting"]
        groups.setdefault(grouping, {})[r["metric"]] = r
    for group_index, (grouping, by_metric) in enumerate(groups.items()):
        assert set(by_metric) == set(metrics)
        if group_index:
            lines.append(r"\midrule[0.3pt]")
        first = by_metric[metrics[0]]
        for method_index, prefix in enumerate(prefixes):
            # Neutral scenario banding, never a colour encoding of performance.
            if group_index % 2:
                lines.append(r"\rowcolor[gray]{0.96}")
            label = grouping if method_index == 0 else ""
            n = f'{first["n_compounds"]:,}' if method_index == 0 else ""
            method = {"raw":"Raw", "comparator":first["comparator_method"],
                      "difference":r"\textit{Difference}"}[prefix]
            if prefix == "comparator":
                method = {"CFRA":"ReCA", "CFRA+Res":"ReCA+Res"}.get(method, method)
            cells = []
            for metric in metrics:
                r = by_metric[metric]
                better = (r["comparator_mean"] < r["raw_mean"] if metric == "raw_target_rmse"
                          else r["comparator_mean"] > r["raw_mean"])
                tie = r["comparator_mean"] == r["raw_mean"]
                bold = prefix != "difference" and not tie and (
                    (prefix == "comparator" and better) or (prefix == "raw" and not better))
                cells.append(cell(r, prefix, signed=prefix == "difference", bold=bold))
            row_end = r" \\[12pt]" if prefix == prefixes[-1] else r" \\[4pt]"
            lines.append(" & ".join([r"\rule{0pt}{12pt}"+label,n,method]+cells)+row_end)
    return "\n".join(lines)


def main_notes(rows):
    e_n = [f'{r["n_compounds"]:,}' for r in rows if r["metric"] == "E"]
    assert len(e_n) == 3
    return (r"Values are means with pointwise 95\% bootstrap confidence intervals below. $n$ denotes compounds "
        r"evaluated by PCC, $\Delta$PCC and RMSE; $E$ requires matched references from other compounds and was "
        rf"evaluated on {e_n[0]}, {e_n[1]} and {e_n[2]} compounds at 2R, 3R and 4R, respectively. "
        r"PCC, Pearson correlation coefficient computed on full profiles; $\Delta$PCC, Pearson correlation "
        r"coefficient computed on control-subtracted responses; RMSE, root mean squared error; "
        r"$E$, perturbation specificity (Fisher $z$). "
        r"Res, residual prediction. $\uparrow$/$\downarrow$ indicate higher/lower is better. Bold marks the "
        r"better mean within each setting. Target construction, seed aggregation "
        r"and resampling are described in Methods.")


MAIN_START = (r"\newcommand{\ReCATableStart}{\begin{tabular}{p{13mm}p{11mm}p{19mm}"
              r"*{4}{p{\dimexpr(\linewidth-43mm-14\tabcolsep)/4\relax}}}}")


SUPP_NOTES = r"""Raw (M0) and ReCA (M1) are capacity-matched predictors evaluated on the same raw target. Values are means with pointwise 95\% CIs below. $\uparrow$/$\downarrow$ indicate higher/lower is better. Bold denotes the better method mean within each setting, not statistical significance. Difference rows show ReCA minus Raw; negative RMSE differences indicate improvement. Each drug contributes its dose-averaged score from the original five-seed prediction ensemble. $n$ denotes drugs within the indicated target line; the same drug can occur in multiple target-line evaluations.

PCC is full-profile correlation after adding the matched Vehicle baseline; $\Delta$PCC is correlation of the control-subtracted response. RMSE is the square root of each condition's saved MSE, averaged across doses within drug and then drugs, not the square root of the aggregate MSE. It is a supplementary post-hoc metric on frozen outputs, with no refitting. These cross-cell results are historical evaluations. All CIs use 10,000 paired-drug resamples and are not multiplicity-adjusted. Original correlation values and paired intervals are retained; RMSE and own-arm intervals use the saved within-target-line bootstrap indices. Extra precision is retained where rounding would obscure an interval's sign."""


MAIN_TITLE = "Raw-profile prediction with reproducibility-aware supervision"


def main_body(main):
    s = block_header("BBBC047: selected-repeat reconstruction","Budget",BB_METRICS)+"\n"
    s += data_rows(main,show_difference=False,metrics=BB_METRICS)+"\n"
    return s


def make_table(main, supplemental=False):
    title = "Cell-line-resolved sci-Plex3 prediction with ReCA-derived supervision" if supplemental else MAIN_TITLE
    label = "tab:predictor-celllines" if supplemental else "tab:predictor-supervision"
    preamble = PREAMBLE if supplemental else "\n".join(
        MAIN_START if line.startswith(r"\newcommand{\ReCATableStart}") else line for line in PREAMBLE.split("\n"))
    s = preamble + "\n" + r"\begin{table}[p]" + "\n" + r"\centering" + "\n"
    s += r"\caption["+title+r"]{\textbar\enspace "+title+"}\n"+r"\label{"+label+"}\n"
    s += r"\fontsize{8.5}{10}\selectfont"+"\n"+r"\ReCATableStart"+"\n"+r"\toprule[0.7pt]"+"\n"
    if supplemental:
        for i,setting in enumerate(("Unseen","Seen")):
            if i:
                s += "\n"+r"\midrule[0.7pt]"+"\n"
            s += block_header("sci-Plex3: "+setting.lower()+"-drug cross-cell transfer","Target cell")+"\n"
            s += data_rows([r for r in main if r["setting"]==setting],True)+"\n"
    else:
        s += main_body(main)
    s += r"\bottomrule[0.7pt]"+"\n"+r"\end{tabular}"+"\n"
    s += r"\par\vspace{5pt}\begin{minipage}{\linewidth}\fontsize{7.5}{9.2}\selectfont\raggedright"+"\n"
    s += (SUPP_NOTES if supplemental else main_notes(main))+"\n"
    s += r"\end{minipage}"+"\n"+r"\end{table}"+"\n"+r"\endgroup"+"\n"
    return s


def make_inline_table(main):
    """Variant pasted into the single-file Manuscript.tex (manual caption, no caption package)."""
    body = [line for line in PREAMBLE.split("\n")
            if line.startswith(("\\begingroup", "\\sffamily", "\\setlength", "\\renewcommand",
                                "\\arrayrulecolor", "\\newcommand{\\ReCATableCell}", "\\newcommand{\\ReCATableHead}"))]
    s = "\n".join([
        "% BEGIN predictor table integration",
        "% Generated by tables/predictor/scripts/build_predictor_table.py from frozen metrics.",
        "% Do not edit individual numeric cells; regenerate and paste instead.",
        "% Inline submission variant: manual caption avoids changing other figure captions.",
        *body, MAIN_START, "",
        r"\begin{table}[!htbp]", r"\centering",
        r"\refstepcounter{table}\label{tab:predictor-supervision}",
        r"\noindent\makebox[\linewidth][l]{{\fontsize{10}{12}\selectfont\textbf{Table \thetable\enspace|\enspace "
        + MAIN_TITLE + r"}}}\par\vspace{7pt}",
        r"\fontsize{8.5}{10}\selectfont", r"\ReCATableStart", r"\toprule[0.7pt]"]) + "\n"
    s += main_body(main)
    s += r"\bottomrule[0.7pt]"+"\n"+r"\end{tabular}"+"\n"
    s += r"\par\vspace{5pt}\begin{minipage}{\linewidth}\fontsize{8}{10}\selectfont\raggedright"+"\n"
    s += main_notes(main)+"\n"+r"\end{minipage}"+"\n"+r"\end{table}"+"\n"+r"\endgroup"+"\n"
    s += "% END predictor table integration\n"
    return s


SC_LABELS = {"own_cell_unseen": "Within cell line, unseen drugs",
             "cross_cell_unseen": "Across cell lines, unseen drugs",
             "cross_cell_seen": "Across cell lines, seen drugs"}


def sci_value(v, signed=False):
    # Text-mode digits match the sans-serif body; same minus handling as number().
    return number(v, 4, signed)


def make_sciplex_table(rows):
    """Supplementary longtable with every sci-Plex3 surface, arm and metric."""
    by = {(r["surface"], r["metric"]): r for r in rows}
    head = (r"\textbf{Training target} & \textbf{PCC $\uparrow$} & \textbf{$\Delta$PCC $\uparrow$} & "
            r"\textbf{$E$ $\uparrow$} \\")
    s = "\n".join([
        "% Generated by tables/predictor/scripts/build_predictor_table.py from frozen metrics.",
        "% Do not edit individual numeric cells; regenerate and paste instead.",
        r"\subsection*{Supplementary Table S6 | sci-Plex3 prediction with ReCA-derived training targets}",
        r"\begingroup", r"\fontsize{10.5}{12.5}\selectfont", r"\setlength{\tabcolsep}{4pt}",
        r"\renewcommand{\arraystretch}{1.14}",
        r"\begin{longtable}{@{}P{70mm}P{58mm}P{58mm}P{58mm}@{}}", r"\toprule", head, r"\midrule",
        r"\endfirsthead", r"\multicolumn{4}{l}{\textbf{Supplementary Table S6 continued}} \\[4pt]",
        r"\toprule", head, r"\midrule", r"\endhead", r"\bottomrule", r"\endlastfoot"]) + "\n"
    for i, surface in enumerate(SC_SURFACES):
        n = by[(surface, SC_METRICS[0])]["n_drugs_per_target_line"]
        if i:
            s += r"\addlinespace[4pt]" + "\n"
        s += (r"\rowcolor{black!5}\multicolumn{4}{l}{\textbf{" + SC_LABELS[surface]
              + rf" ({n} drugs per target cell line)" + r"}} \\" + "\n")
        for label, key in (("Raw (observed responses)", None), ("ReCA", "reca"), ("ReCA+Res", "reca_res")):
            cells = []
            for metric in SC_METRICS:
                r = by[(surface, metric)]
                if key is None:
                    cells.append(sci_value(r["raw_mean"]))
                else:
                    cells.append(sci_value(r[key + "_mean"]) + r"\newline "
                                 + sci_value(r[key + "_minus_raw"], True) + r" [" + sci_value(r[key + "_minus_raw_ci_low"], True)
                                 + r", " + sci_value(r[key + "_minus_raw_ci_high"], True) + "]")
            s += label + " & " + " & ".join(cells) + r" \\[2pt]" + "\n"
    s += r"\end{longtable}" + "\n" + r"\endgroup" + "\n"
    s += (r"{\fontsize{10.5}{12.5}\selectfont " + SC_NOTES + r"\par}" + "\n")
    return s


