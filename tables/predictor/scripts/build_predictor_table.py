def read(path):
    with path.open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def assert_close(a, b, label):
    if not math.isclose(float(a), float(b), rel_tol=0, abs_tol=2e-10):
        raise AssertionError(f"{label}: {a} != {b}")


def record(dataset, setting, line, n, metric, method, raw, cfra, diff):
    assert_close(cfra[0] - raw[0], diff[0], "paired difference")
    for trio in (raw, cfra, diff):
        assert all(math.isfinite(v) for v in trio)
        assert trio[1] <= trio[2]
    return dict(dataset=dataset, setting=setting, target_line=line, n_compounds=n,
        metric=metric, comparator_method=method, raw_mean=raw[0], raw_ci_low=raw[1],
        raw_ci_high=raw[2], comparator_mean=cfra[0], comparator_ci_low=cfra[1],
        comparator_ci_high=cfra[2], difference=diff[0], difference_ci_low=diff[1],
        difference_ci_high=diff[2], bootstrap_draws=10000,
        ci_unit="compound" if dataset == "BBBC047" else "drug_within_target_line",
        ci_status="pointwise_95_percent",
        preferred_direction="lower" if metric=="raw_target_rmse" else "higher",
        metric_status="posthoc_frozen_prediction_supplement" if metric=="raw_target_rmse" else "original_frozen_endpoint")


def load_data():
    inputs = [BB / "TEST_METHOD_SUMMARY.csv", BB / "TEST_CONTRASTS.csv",
        SC / "SURFACE_MACRO_FULL_COMPARISON.csv", SC / "CONFIRMATION_CONTRASTS_ALL.csv",
        F5 / "bc_sciplex3_arm_means_and_ci.csv", F5 / "data_audit.json",
        ROOT / "tables/predictor/inputs/rmse/RMSE_SUMMARY.csv", ROOT / "tables/predictor/inputs/rmse/RMSE_AUDIT.json"]
    bba = {(int(r["budget"]), r["method"]):r for r in read(inputs[0])}
    bbc = {(int(r["budget"]), r["metric"]):r for r in read(inputs[1])}
    macro = {(r["surface"],r["metric"]):r for r in read(inputs[2])}
    contrasts = {(r["surface"],r["target_cell_line"],r["metric"]):r
        for r in read(inputs[3]) if r["comparison"] == CFRA + " - " + RAW}
    own = {(r["surface"],r["target_cell_line"],r["metric"],r["method"]):r
        for r in read(inputs[4]) if r["method"] in (RAW,CFRA)}
    rmse = {(r["dataset"],r["setting"],r["target_line"]):r for r in read(inputs[6])}
    rmse_audit = json.loads(inputs[7].read_text(encoding="utf-8"))
    assert rmse_audit["status"]=="PASS" and rmse_audit["no_sqrt_of_aggregate_mse"]
    assert rmse_audit["summary_sha256"]==sha(inputs[6])
    # The own-arm CI file was generated by replaying the frozen macro indices.
    prior = json.loads(inputs[5].read_text(encoding="utf-8"))
    assert prior["status"] == "PASS" and prior["paired_frozen_means_and_ci_verified"]
    for p in (inputs[0], inputs[1], inputs[2]):
        # Audit paths were recorded on Windows; parse them portably.
        matching = [r for r in prior["source_files"] if PureWindowsPath(r["path"]).name == p.name]
        assert len(matching) == 1 and matching[0]["sha256"] == sha(p)

    def arm(r, metric=None):
        if metric:
            return tuple(float(r[metric + suffix]) for suffix in ("_mean","_ci_low","_ci_high"))
        return tuple(float(r[k]) for k in ("mean","ci_low","ci_high"))

    def rmse_record(dataset,setting,line):
        r=rmse[(dataset,setting,line)]
        a=tuple(float(r[k]) for k in ("raw_mean","raw_ci_low","raw_ci_high"))
        b=tuple(float(r[k]) for k in ("comparator_mean","comparator_ci_low","comparator_ci_high"))
        d=tuple(float(r[k]) for k in ("difference","difference_ci_low","difference_ci_high"))
        return record(dataset,setting,line,int(r["n_compounds"]),"raw_target_rmse",r["comparator_method"],a,b,d)

    main, extended, sciplex = [], [], []
    for budget in (2,3,4):
        for metric in BB_METRICS:
            if metric=="raw_target_rmse":
                main.append(rmse_record("BBBC047",f"{budget}R",""))
                continue
            raw = bba[(budget,"M0_RawKAggregate")]
            m2 = bba[(budget,"M2_CFRA1ViewAggregate_Residual")]
            delta = bbc[(budget,metric)]
            # E requires matched foreign references, so its eligible set is smaller.
            n = int(raw["E_n"]) if metric == "E" else int(raw["n_compounds"])
            assert int(delta["n_compounds"]) == n
            main.append(record("BBBC047",f"{budget}R","",n,metric,
                "CFRA+Res",arm(raw,metric),arm(m2,metric),
                tuple(float(delta[k]) for k in ("estimate","ci_low","ci_high"))))
    for surface in SC_SURFACES:
        for metric in SC_METRICS:
            m = macro[(surface,metric)]
            assert m["n_target_lines"] == "3"
            row = dict(dataset="sci-Plex3", surface=surface, historical_status=m["historical_status"],
                n_drugs_per_target_line=int(m["n_drugs_macro_basis"]), metric=metric,
                raw_mean=float(m[RAW+"_value"]), reca_mean=float(m[CFRA+"_value"]),
                reca_res_mean=float(m[RES+"_value"]))
            for arm_key, prefix in (("reca", "M1_minus_M0"), ("reca_res", "M2_minus_M0")):
                trio = tuple(float(m[prefix+s]) for s in ("_estimate","_ci_low","_ci_high"))
                assert all(math.isfinite(v) for v in trio) and trio[1] <= trio[2]
                assert_close(row[arm_key+"_mean"] - row["raw_mean"], trio[0], prefix)
                row.update({arm_key+"_minus_raw": trio[0], arm_key+"_minus_raw_ci_low": trio[1],
                            arm_key+"_minus_raw_ci_high": trio[2]})
            row.update(bootstrap_draws=int(m["bootstrap_draws"]), ci_unit="drug_within_target_line",
                       ci_status="pointwise_95_percent", preferred_direction="higher",
                       metric_status="original_frozen_endpoint")
            sciplex.append(row)
    for surface in SURFACES:
        setting = "Unseen" if surface.endswith("unseen") else "Seen"
        n = 36 if setting == "Unseen" else 183
        for line in LINES:
            for metric in METRICS:
                if metric=="raw_target_rmse":
                    extended.append(rmse_record("sci-Plex3",setting,line))
                    continue
                r = own[(surface,line,metric,RAW)]
                c = own[(surface,line,metric,CFRA)]
                d = contrasts[(surface,line,metric)]
                assert int(d["n_drugs"]) == n
                extended.append(record("sci-Plex3",setting,line,n,metric,"CFRA",
                    arm(r),arm(c),tuple(float(d[k]) for k in ("estimate","ci_low","ci_high"))))
    assert len(main) == 12 and len(extended) == 18 and len(sciplex) == 9
    assert all(r["dataset"] == "BBBC047" for r in main)
    assert set(r["metric"] for r in main) == set(BB_METRICS)
    assert set(r["metric"] for r in extended) == set(METRICS)
    assert all(r["comparator_method"] == "CFRA" for r in extended)
    audit = dict(status="PASS",main_rows=len(main),supplement_rows=len(extended),
        sciplex_matrix_rows=len(sciplex),
        main_table_datasets=["BBBC047"],
        bbbc047_displayed_arms=["Raw (M0)","ReCA+Res (M2)"],
        bbbc047_displayed_metrics=["PCC","deltaPCC","RMSE","E"],
        sciplex_matrix_surfaces=list(SC_SURFACES),
        sciplex_matrix_arms=["Raw (M0)","ReCA (M1)","ReCA+Res (M2)"],
        sciplex_matrix_metrics=["PCC","deltaPCC","E"],
        celllines_table_arms=["Raw (M0)","ReCA (M1)"],original_results_unchanged=True,
        own_arm_ci_in_every_source_record=True,paired_ci_in_every_source_record=True,
        main_display_rows=6,supplement_display_rows=18,
        main_difference_rows_displayed=False,main_differences_moved_to_supplement=False,
        sciplex_own_ci_source="previous audited replay of frozen within-line macro bootstrap indices",
        no_training_or_selection=True,supplementary_rmse_added=True,
        frozen_correlation_values_and_cis_unchanged=True,
        preferred_directions={"PCC":"up","deltaPCC":"up","RMSE":"down"},
        inputs=[dict(path=str(p.relative_to(ROOT)),sha256=sha(p)) for p in inputs])
    return main, extended, sciplex, audit


def number(v, digits, signed=False):
    s = f"{v:+.{digits}f}" if signed else f"{v:.{digits}f}"
    return s.replace("-", r"\ensuremath{-}")


def cell(r, prefix, signed=False, bold=False):
    keys = ("difference","difference_ci_low","difference_ci_high") if prefix == "difference" else (
        prefix+"_mean",prefix+"_ci_low",prefix+"_ci_high")
    digits = 4
    # Never let rounding erase the sign of a nonzero confidence bound.
    while any(r[k] != 0 and round(r[k],digits) == 0 for k in keys):
        digits += 1
    nums = [number(r[k],digits,signed and i==0) for i,k in enumerate(keys)]
    if bold:
        nums[0] = r"\textbf{" + nums[0] + "}"
    return r"\ReCATableCell{" + "}{".join(nums) + "}"


